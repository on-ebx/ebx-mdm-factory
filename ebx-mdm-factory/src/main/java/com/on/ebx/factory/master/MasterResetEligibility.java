package com.on.ebx.factory.master;

/**
 * Whether {@code ebx.MasterReset} may actually close and delete a project's GREENFIELD master zone
 * (`docs/MASTER-ZONE.md`, 2026-09-21 incident: {@code Company}, {@code Supplier} and {@code Account} were
 * promoted together by mistake; removal is NON-ADDITIVE, so {@code master.MasterModelState}'s own
 * regeneration path rightly refuses to drop {@code Supplier}/{@code Account} on its own - a reset is the only
 * way out). Every condition below is a separate, deliberately narrow guard - this is a one-shot recovery tool
 * for a factory-generated GREENFIELD mistake, never a general "delete any dataspace" mechanism:
 * <ol>
 * <li>the project must be {@code GREENFIELD} (a {@code TARGET_EXISTS} project's master is not this factory's
 * to delete);</li>
 * <li>it must actually have a master zone to reset (blank {@code masterDataspace} -&gt; nothing to do);</li>
 * <li>{@code Project.masterDataspace}/{@code masterDataset} must be EXACTLY the names {@code
 * master.MasterNames} would compute for this project - the same comparison {@code MasterTargetDecision}
 * already makes for generation, applied here to deletion: a foreign value (the demo project's own hand-typed
 * {@code TestMasterDataspace}/{@code TestMasterDataset}) is never a candidate, whatever else is true;</li>
 * <li>there must be live {@code PipelineStep} evidence that MASTER_MODEL and MASTER_DATASET actually ran for
 * this project, with MASTER_DATASET's own detail recording that the dataspace was CREATED by the factory
 * (not merely found already existing under a name that happens to match) - a coincidence of naming alone is
 * not enough to justify deleting something;</li>
 * <li>the add-on's own matching metadataset ({@code MameMetadataset}, one per promoted master TABLE, {@code
 * &lt;dataset&gt;_&lt;table&gt;_MDS} in the master dataspace - fixed 2026-09-22, see that class' own Javadoc;
 * the caller checks EVERY promoted table, not just one) must NOT exist for any of them - if matching has ever
 * been activated on any master table, a reset could discard real match/merge history, which this tool refuses
 * to touch rather than guess is safe;</li>
 * <li>the caller must pass {@code confirm} equal to the master dataspace key, exactly.</li>
 * </ol>
 * Pure: no EBX class - {@code ebx.MasterReset} does every read (project fields, {@code PipelineStep} history,
 * whether the metadataset exists) and hands in the resulting plain values; this class only decides and builds
 * the refusal message, so every branch is unit-tested without a running instance.
 */
public final class MasterResetEligibility
{
	private MasterResetEligibility()
	{
	}

	public static final class Decision
	{
		public final boolean allowed;
		/** Non-null only when {@link #allowed} is false. */
		public final String refusal;

		private Decision(final boolean pAllowed, final String pRefusal)
		{
			this.allowed = pAllowed;
			this.refusal = pRefusal;
		}
	}

	public static Decision decide(final String pProjectCode, final String pMode, final String pExistingDataspace, final String pExistingDataset,
		final String pComputedDataspace, final String pComputedDataset, final boolean pMasterModelStepEverDone, final boolean pMasterDatasetCreatedByFactory,
		final boolean pMetadatasetExists, final String pConfirm)
	{
		if (!"GREENFIELD".equals(pMode))
		{
			return MasterResetEligibility
				.refuse("Project " + pProjectCode + " is mode " + pMode + ": only a GREENFIELD project's master zone (generated by this factory) can be reset.");
		}
		final boolean blank = pExistingDataspace == null || pExistingDataspace.trim().isEmpty();
		if (blank)
		{
			return MasterResetEligibility.refuse("Project " + pProjectCode + " has no master zone to reset.");
		}
		final String existingDataset = pExistingDataset == null ? "" : pExistingDataset.trim();
		final boolean isFactoryNamed = pComputedDataspace.equals(pExistingDataspace.trim()) && pComputedDataset.equals(existingDataset);
		if (!isFactoryNamed)
		{
			return MasterResetEligibility.refuse("Project " + pProjectCode + "'s masterDataspace/masterDataset (" + pExistingDataspace + "/" + pExistingDataset
				+ ") is not the name this factory would itself generate (" + pComputedDataspace + "/" + pComputedDataset
				+ "): never resetting a dataspace this factory did not create - if it needs to go, do it by hand.");
		}
		if (!pMasterModelStepEverDone || !pMasterDatasetCreatedByFactory)
		{
			return MasterResetEligibility.refuse("Project " + pProjectCode
				+ " has no PipelineStep evidence that MASTER_MODEL ran and MASTER_DATASET actually CREATED the dataspace (as opposed to finding one that already "
				+ "existed under a matching name): refusing to guess at ownership from the name alone.");
		}
		if (pMetadatasetExists)
		{
			return MasterResetEligibility.refuse("Project " + pProjectCode
				+ "'s master zone already has a Match and Merge metadataset for at least one of its promoted tables (dataspace " + pComputedDataspace
				+ ", one metadataset per table named <" + pComputedDataset
				+ ">_<table>_MDS): resetting could discard real match/merge history, not attempted here. To reset anyway, first remove the matching configuration by hand for "
				+ "every promoted table (the match-merge MCP server's delete_matching_config - a real teardown, not reversible, see its own tool description for exactly "
				+ "what it deletes) or set MatchPlan back to PROPOSED and re-run POST /projects/" + pProjectCode + "/matching/configure once this reset has run, "
				+ "whichever the situation calls for.");
		}
		final String expectedConfirm = pExistingDataspace.trim();
		if (pConfirm == null || !pConfirm.equals(expectedConfirm))
		{
			return MasterResetEligibility.refuse("Pass ?confirm=" + expectedConfirm + " (the exact master dataspace key) to actually reset project " + pProjectCode
				+ "'s master zone - this closes and deletes the dataspace and the data model, and cannot be undone.");
		}
		return new Decision(true, null);
	}

	private static Decision refuse(final String pMessage)
	{
		return new Decision(false, pMessage);
	}
}
